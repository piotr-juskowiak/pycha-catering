function pychaParseMenuTimestamp(value) {
  const parsed = Date.parse(value);
  return Number.isFinite(parsed) ? parsed : 0;
}

function pychaStripPdfQuantityMarks(menu) {
  if (!menu || typeof menu !== 'object' || !menu.weeklyMenu) return menu;
  Object.values(menu.weeklyMenu).forEach((week) => {
    if (!week || typeof week !== 'object') return;
    Object.values(week).forEach((day) => {
      if (!day || typeof day !== 'object') return;
      Object.values(day).forEach((items) => {
        if (!Array.isArray(items)) return;
        items.forEach((item) => {
          if (!item || typeof item !== 'object') return;
          if (/^\d+$/.test(String(item.weight || '').trim())) item.weight = '';
        });
      });
    });
  });
  return menu;
}

pychaStripPdfQuantityMarks(window.PYCHA_MENU_DATA);

// Use the online copy only when it is newer than this file.
// An older Redis snapshot must not overwrite the current menu.
window.PYCHA_MENU_DATA_READY = fetch('/api/menu', {
  method: 'GET',
  headers: { Accept: 'application/json' },
  cache: 'no-store',
})
  .then(async (response) => {
    if (!response.ok) throw new Error(`Nie udało się pobrać menu (${response.status}).`);
    const payload = await response.json();
    if (!payload.menu || typeof payload.menu !== 'object') {
      throw new Error('Serwer zwrócił nieprawidłowe dane menu.');
    }
    const bundledAt = pychaParseMenuTimestamp(window.PYCHA_MENU_BUNDLED_AT);
    const remoteAt = pychaParseMenuTimestamp(payload.updatedAt || payload.menu.updatedAt);
    if (remoteAt > bundledAt) {
      window.PYCHA_MENU_DATA = payload.menu;
    }
    pychaStripPdfQuantityMarks(window.PYCHA_MENU_DATA);
    return window.PYCHA_MENU_DATA;
  })
  .catch(() => window.PYCHA_MENU_DATA);
